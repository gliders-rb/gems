# frozen_string_literal: true

module FieldStruct
  module Protobuf
    # Prints the +.proto+ source of a file descriptor (PB-B20, PB-B21). The text comes from the descriptor that is
    # registered, so the two cannot disagree (PB-I2).
    class Printer
      SCALARS = {
        TYPE_STRING: 'string', TYPE_BYTES: 'bytes', TYPE_BOOL: 'bool', TYPE_INT64: 'int64', TYPE_DOUBLE: 'double'
      }.freeze
      private_constant :SCALARS

      # @param file [::Object] a +Google::Protobuf::FileDescriptorProto+
      # @param klass [::Class] the struct class the file was built from (named in the header)
      def initialize(file, klass)
        @file = file
        @klass = klass
      end

      # @return [::String] the +.proto+ source, newline-terminated
      def call
        sections = [header, package, imports, message(@file.message_type.first)]
        sections.flatten.join("\n") << "\n"
      end

      private

      def header
        [
          "// #{@file.name}: generated by field_struct-protobuf from #{@klass}.",
          "// Field numbers come from each field's proto: {number:} option.",
          '', 'syntax = "proto3";', ''
        ]
      end

      def package
        @file.package.empty? ? [] : ["package #{@file.package};", '']
      end

      def imports
        return [] if @file.dependency.empty?

        [*@file.dependency.map { |name| %(import "#{name}";) }, '']
      end

      def message(message)
        body = message.field.map { |field| "  #{field_line(field)}" }
        ["message #{message.name} {", *body, '}']
      end

      def field_line(field)
        modifier = if field.label == :LABEL_REPEATED
                     'repeated'
                   elsif field.proto3_optional
                     'optional'
                   end
        [modifier, type_text(field), field.name, '=', "#{field.number};"].compact.join(' ')
      end

      def type_text(field)
        field.type == :TYPE_MESSAGE ? field.type_name : SCALARS.fetch(field.type)
      end
    end
  end
end
