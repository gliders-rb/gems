# frozen_string_literal: true

RSpec.describe 'FieldStruct::Protobuf nested structs and well-known types' do
  def descriptor(klass)
    FieldStruct::Protobuf.file_descriptor(klass)
  end

  def fields_of(klass)
    descriptor(klass).message_type.first.field.to_h { |f| [f.name, f] }
  end

  let(:station) do
    define_struct('Velo::Station') do
      required :district, :string, proto: { number: 1 }
      optional :dock, :string, proto: { number: 2 }
    end
  end

  let(:trip) do
    addr = station
    define_struct('Velo::Trip') do
      required :id, :integer, proto: { number: 1 }
      optional :at, :time, proto: { number: 2 }
      optional :end_dock, addr, proto: { number: 8 }
      optional :extras, :value, proto: { number: 9 }
      optional :stops, :array, of: addr, proto: { number: 13 }
      optional :pings, :array, of: :time, proto: { number: 15 }
    end
  end

  before do
    station
    trip.optional :prior, trip, proto: { number: 14 }
  end

  describe 'descriptor shape (PB-B5, PB-B6, PB-B7, PB-B8)' do
    it 'PB-B5: maps :time and :datetime to a Timestamp message field with message presence' do
      dt = define_struct('Dt') { required :at, :datetime, proto: { number: 1 } }
      [fields_of(trip)['at'], fields_of(dt)['at']].each do |field|
        expect([field.type, field.type_name, field.label]).to eq([:TYPE_MESSAGE, '.google.protobuf.Timestamp', :LABEL_OPTIONAL])
        expect([field.proto3_optional, field.has_oneof_index?]).to eq([false, false])
      end
    end

    it 'PB-B5: maps :value to google.protobuf.Value' do
      field = fields_of(trip)['extras']
      expect([field.type, field.type_name, field.proto3_optional]).to eq([:TYPE_MESSAGE, '.google.protobuf.Value', false])
    end

    it 'PB-B5: maps a struct field to its full name' do
      field = fields_of(trip)['end_dock']
      expect([field.type, field.type_name, field.label, field.proto3_optional]).to eq(
        [:TYPE_MESSAGE, '.velo.Station', :LABEL_OPTIONAL, false]
      )
    end

    it 'PB-B7: maps arrays of structs and of times to repeated messages without oneofs' do
      fields = fields_of(trip)
      expect([fields['stops'].label, fields['stops'].type_name]).to eq([:LABEL_REPEATED, '.velo.Station'])
      expect([fields['pings'].label, fields['pings'].type_name]).to eq([:LABEL_REPEATED, '.google.protobuf.Timestamp'])
      expect(fields['stops'].has_oneof_index?).to be(false)
    end

    it 'PB-B8: refers to itself without importing itself' do
      field = fields_of(trip)['prior']
      expect([field.type_name, field.number]).to eq(['.velo.Trip', 14])
      expect(descriptor(trip).dependency.to_a).not_to include('field_struct/velo/trip.proto')
    end

    it 'PB-B6: lists unique imports in order of first use' do
      expect(descriptor(trip).dependency.to_a).to eq(
        %w[google/protobuf/timestamp.proto field_struct/velo/station.proto google/protobuf/struct.proto]
      )
    end

    it 'PB-B6: only gives oneofs to the singular scalars' do
      expect(descriptor(trip).message_type.first.oneof_decl.map(&:name)).to eq(['_id'])
    end
  end

  describe 'the printed text (PB-B20, PB-B21)' do
    it 'PB-B21: prints imports then message-typed lines with leading-dot names' do
      expect(FieldStruct::Protobuf.proto(trip)).to eq(<<~PROTO)
        // field_struct/velo/trip.proto: generated by field_struct-protobuf from Velo::Trip.
        // Field numbers come from each field's proto: {number:} option.

        syntax = "proto3";

        package velo;

        import "google/protobuf/timestamp.proto";
        import "field_struct/velo/station.proto";
        import "google/protobuf/struct.proto";

        message Trip {
          optional int64 id = 1;
          .google.protobuf.Timestamp at = 2;
          .velo.Station end_dock = 8;
          .google.protobuf.Value extras = 9;
          repeated .velo.Station stops = 13;
          repeated .google.protobuf.Timestamp pings = 15;
          .velo.Trip prior = 14;
        }
      PROTO
    end

    it 'PB-I2: compiles with protoc to an equivalent descriptor, together with the structs it refers to' do
      klasses = [station, trip]
      expect(ProtocCheck.compile(ProtocCheck.texts(klasses))).to eq(ProtocCheck.ours(klasses))
    end
  end

  describe 'refusals and cycles' do
    it 'PB-B9: refuses an anonymous nested struct' do
      anon = Class.new(FieldStruct::Base) { required :a, :string, proto: { number: 1 } }
      klass = define_struct('Holder') { optional :inner, anon, proto: { number: 1 } }
      expect { descriptor(klass) }.to raise_error(
        ArgumentError, "Holder#inner is an anonymous struct (assign it to a constant), which field_struct-protobuf can't map yet"
      )
    end

    it 'PB-B9: refuses an array of anonymous structs' do
      anon = Class.new(FieldStruct::Base) { required :a, :string, proto: { number: 1 } }
      klass = define_struct('Holder') { optional :inners, :array, of: anon, proto: { number: 1 } }
      expect { descriptor(klass) }.to raise_error(ArgumentError, /Holder#inners is an anonymous struct/)
    end

    it 'PB-B10: still prints text and a descriptor for mutually referring structs' do
      pickup = define_struct('Cyc::Pickup') { required :id, :integer, proto: { number: 1 } }
      dropoff = define_struct('Cyc::Dropoff') { optional :pickup, pickup, proto: { number: 1 } }
      pickup.optional :dropoff, dropoff, proto: { number: 2 }
      expect(FieldStruct::Protobuf.proto(pickup)).to include('.cyc.Dropoff dropoff = 2;', 'import "field_struct/cyc/dropoff.proto";')
      expect(descriptor(dropoff).dependency.to_a).to eq(['field_struct/cyc/pickup.proto'])
    end
  end
end
